#!/usr/bin/env node
/**
 * content-dates.mjs — 원고 파일 수정일(마지막 커밋일, KST) 표 (NAVER-SEO-FIX-1031)
 *
 *   node scripts/content-dates.mjs <원고 폴더> <출력 .ts>
 *
 * <원고 폴더>/*.md(x) 마다 "파일명(확장자 뺀 것)" → "YYYY-MM-DD". 커밋 메시지에 [lastmod-skip] 이 든 커밋은 건너뛴다.
 * 커밋 이력이 없는 새 원고는 표에 넣지 않는다(호출부가 원고 date 로 대신한다). 요청 시각(new Date())은 쓰지 않는다.
 * git log 를 파일마다 부르지 않고 한 번에 읽는다(원고 수백 편).
 */
import { readdirSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'

const [dir, out] = process.argv.slice(2)
if (!dir || !out) { console.error('usage: content-dates.mjs <dir> <out.ts>'); process.exit(2) }
const want = new Set(readdirSync(dir).filter((f) => /\.mdx?$/.test(f)).map((f) => join(dir, f)))
const log = execFileSync('git', ['log', '--format=@@%cd', '--date=format-local:%Y-%m-%d', '--name-only',
  '--invert-grep', '--grep=\\[lastmod-skip\\]', '--', dir], { encoding: 'utf8', maxBuffer: 64 << 20, env: { ...process.env, TZ: 'Asia/Seoul' } })
const dates = {}
let cur = ''
for (const line of log.split('\n')) {
  if (line.startsWith('@@')) { cur = line.slice(2); continue }
  const f = line.trim()
  if (!f || !want.has(f)) continue
  const key = f.slice(dir.replace(/\/$/, '').length + 1).replace(/\.mdx?$/, '')
  if (!(key in dates)) dates[key] = cur   // git log 는 최신순 — 처음 본 날짜가 마지막 수정일
}
writeFileSync(out, `// GENERATED by scripts/content-dates.mjs — 손으로 고치지 않는다(원고 마지막 커밋일, [lastmod-skip] 제외).
export const CONTENT_MODIFIED: Record<string, string> = ${JSON.stringify(dates, null, 2)};
`)
console.log(`[content-dates] ${Object.keys(dates).length}/${want.size}편 → ${out}`)
